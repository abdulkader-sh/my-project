package com.hisnaladhkar.app.domain.model

/**
 * أبعاد التصنيف المستقلة: نفس الذكر يمكن أن ينتمي لعدة تصنيفات
 * عبر أكثر من بُعد في نفس الوقت (علاقة Many-to-Many في [DhikrCategoryCrossRef]).
 */
enum class CategoryDimension {
    TIME_OCCASION,  // حسب الوقت/المناسبة: أذكار الصباح، المساء، النوم...
    THEME,          // حسب المعنى/الموضوع: الاستغفار، الشكر، الكرب...
    POPULAR,        // الأكثر شهرة وتداولاً (باجتهاد محتوى، لا عداد استخدام آلي)
    SOURCE          // حسب المصدر: حصن المسلم، الأذكار للنووي، القرآن الكريم...
}
